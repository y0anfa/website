defmodule Site.Transitions do
  @moduledoc """
  The generated half of the page transitions (SPEC section 7, Transitions).

  In the `morph` prototype the log title that was clicked glides into the entry's
  `h1`. For that, the two elements need the same `view-transition-name`, and the
  name must be unique on each page. The home has one log title per entry, so the
  name comes from the entry's slug (unique across all types, SPEC section 5).

  The names cannot be inline styles (the CSP forbids them), so:

    * the templates add the class `vt-<slug>` to the log title link (`_log`) and to
      the `h1` of the article and project pages, and
    * the build writes `assets/css/transitions.css`, one rule per entry:

          :root[data-vt="morph"] .vt-<slug> {
            view-transition-name: entry-<slug>;
          }

  Both prefixes keep the identifier valid CSS whatever the slug looks like: an
  identifier cannot start with a digit, and `vt-2026-recap` does. Slugs are
  validated as kebab-case (`Site.Content`), and anything else raises here instead
  of producing a rule that would silently match nothing.

  The sheet is plain text built from the loaded content in slug order, with no
  timestamps, so it is part of the deterministic build. If the `morph` prototype
  is not kept, this module, its stylesheet link and the two classes are deleted.
  """

  alias Site.{Content, Entry}

  @file_path "assets/css/transitions.css"
  @slug ~r/\A[a-z0-9]+(?:-[a-z0-9]+)*\z/

  @doc "Output file of the stylesheet, relative to the output directory."
  @spec file_path() :: Path.t()
  def file_path, do: @file_path

  @doc "Every file this module generates, as `{relative file path, data}`."
  @spec files(Content.t()) :: [{Path.t(), String.t()}]
  def files(%Content{} = content), do: [{@file_path, css(Content.entries(content))}]

  @doc """
  The class the templates put on a slug's log title and `h1`.

      iex> Site.Transitions.class("rhino")
      "vt-rhino"
      iex> Site.Transitions.class("2026-recap")
      "vt-2026-recap"
  """
  @spec class(String.t()) :: String.t()
  def class(slug), do: "vt-" <> check!(slug)

  @doc """
  The `view-transition-name` the stylesheet gives that class.

      iex> Site.Transitions.name("rhino")
      "entry-rhino"
  """
  @spec name(String.t()) :: String.t()
  def name(slug), do: "entry-" <> check!(slug)

  @doc """
  The stylesheet: a short header, then one rule per entry, in slug order. The
  rules are scoped to `:root[data-vt="morph"]`, so the other prototypes (and a
  browser without view transitions) ignore the classes.
  """
  @spec css([Entry.t()]) :: String.t()
  def css(entries) do
    rules =
      entries
      |> Enum.map(& &1.slug)
      |> Enum.sort()
      |> Enum.map(&rule/1)

    Enum.join([header() | rules], "\n")
  end

  defp header do
    """
    /* Generated by the build (Site.Transitions). Do not edit.
       One rule per entry: its log title on the home and its h1 on its own page share
       a view-transition-name, so the title glides into the heading (SPEC section 7). */
    """
  end

  defp rule(slug) do
    """
    :root[data-vt="morph"] .#{class(slug)} {
      view-transition-name: #{name(slug)};
    }
    """
  end

  defp check!(slug) when is_binary(slug) do
    if Regex.match?(@slug, slug) do
      slug
    else
      raise ArgumentError,
            "slug #{inspect(slug)} cannot name a view transition: " <>
              "expected lowercase letters, digits and hyphens"
    end
  end
end
